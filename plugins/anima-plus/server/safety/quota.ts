/**
 * 资源配额（plugins/anima-plus/docs/safety.md §8）。
 *
 * 与 `limits.ts` 的分工：
 *   - `limits.ts`：**图里的值** —— 单个任务会不会打爆显存（步数、尺寸、LoRA 数）
 *   - `quota.ts` ：**服务自身的资源** —— 队列、任务表、请求体
 *
 * 两者都是"服务端说了算"，前端只是提示。
 */

/**
 * 允许同时在途（created/queued/running）的任务数上限。
 *
 * 为什么要有：ComfyUI 是单卡串行执行的，排到第 20 个的任务对用户来说
 * 和挂了没区别 —— 而且他还会以为是自己网络问题，反复重试。
 * 到顶直接 429，比让它静静躺在队列里诚实。
 */
export const MAX_QUEUE_DEPTH = 5;

/**
 * 任务表（内存 Map）保留的最大条数，超出时**从最旧的开始丢**。
 *
 * 任务历史是刻意不持久化的（见 README「任务历史：刻意不持久化」），
 * 所以丢掉的只是"本次会话记录"，产出图本身还在 ComfyUI 的 output 目录里，
 * 只是刷新页面后列表里不再显示。
 * 在途任务永远不会被丢。
 */
export const MAX_JOBS_RETAINED = 200;

/**
 * 请求体上限。
 *
 * 原来给到 32 MB 是为了将来可能的图生图上传；现在明确**不做图生图**，
 * 最大的正常请求就是一坨提示词 + LoRA 列表（几 KB），所以收到 256 KB。
 * 一个人不再能靠一个请求吃掉几十 MB 内存。
 */
export const MAX_BODY_BYTES = 256 * 1024;
